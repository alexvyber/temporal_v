"""Generate codec-only activation traversal from the generated protobuf type graph.

Only types reachable from Core activation jobs are emitted. This preserves
unknown fields, repeated-payload codec cardinality and singular map entries.
Search attributes and propagator-owned headers remain untouched.
"""
import argparse,re
from format_v import formatted_source
from pathlib import Path

def generate(root):
 source=(root/'temporal/core_pb.v').read_text();structs={}
 for name,body in re.findall(r'^pub struct (\w+) \{\n(.*?)^\}',source,re.M|re.S):
  structs[name]=[match.groups() for line in body.splitlines() if (match:=re.match(r'^\t(\w+)\s+([^ /]+)',line))]
 sums={name:re.findall(r'\b\w+\b',body) for name,body in re.findall(r'^pub type (\w+) = ([^\n]+(?:\n\s+\|[^\n]+)*)',source,re.M)}
 def base(value):return value.replace('map[string]','').replace('[]','').lstrip('?&')
 relevant={'TemporalApiCommonV1_Payload'}
 while True:
  before=len(relevant)
  for name,fields in structs.items():
   if name!='TemporalApiCommonV1_SearchAttributes' and any(base(kind) in relevant for _,kind in fields):relevant.add(name)
  for name,variants in sums.items():
   if any(variant in relevant for variant in variants):relevant.add(name)
  if len(relevant)==before:break
 needed=set()
 def visit(name):
  if name not in relevant or name in needed:return
  needed.add(name)
  for child in sums.get(name,[]):visit(child)
  for _,kind in structs.get(name,[]):visit(base(kind))
 visit('CoresdkWorkflowActivation_WorkflowActivationJob')
 def function(name):return 'activation_decode_'+name.lower()
 def convert(kind,expression):return f'{function(kind)}({expression}, converter, depth + 1)!'
 lines=['// Generated by scripts/generate_activation_decoder.py. Do not edit.', 'module sdk','','import temporal','']
 for name in sorted(needed):
  lines += [f'fn {function(name)}(value temporal.{name}, converter DataConverter, depth int) !temporal.{name} {{'," if depth > 512 { return error('activation observation payload recursion exceeds schema traversal bound') }"]
  if name=='TemporalApiCommonV1_Payload':
   lines += [' decoded := converter.decode_payloads([value])!'," if decoded.len != 1 { return error('singular activation payload codec requires exactly one payload') }",' return decoded[0]','}',''];continue
  if name in sums:
   lines += [' match value {']
   for variant in sums[name]:
    if variant in needed:lines.append(f' temporal.{variant} {{ return {convert(variant,"value")} }}')
   if any(variant not in needed for variant in sums[name]):lines += [' else { return value }']
   lines += [' }','}',''];continue
  lines += [' mut result := value']
  for field,kind in structs[name]:
   child=base(kind)
   if child not in needed:continue
   source='value.'+field;target='result.'+field
   if kind.startswith('?'):
    lines += [f' if field_value := {source} {{']
    if kind.startswith('?&'):
     lines += [f' nested := {convert(child,"*field_value")}',f' {target} = &nested']
    else:lines += [f' {target} = {convert(child,"field_value")}']
    lines += [' }']
   elif kind.startswith('[]'):
    if child=='TemporalApiCommonV1_Payload':lines += [f' {target} = converter.decode_payloads({source})!']
    else:lines += [f' {target} = []temporal.{child}{{}}',f' for nested in {source} {{ {target} << {convert(child,"nested")} }}']
   elif kind.startswith('map[string]'):
    local='decoded_'+field
    lines += [f' mut {local} := map[string]temporal.{child}{{}}',f' mut keys_{field} := {source}.keys()',f' keys_{field}.sort()',f' for key in keys_{field} {{']
    if field=='headers':lines += [f' if key == trace_header_key {{ {local}[key] = {source}[key]; continue }}']
    lines += [f' {local}[key] = {convert(child,source+"[key]")}', ' }',f' {target} = {local}']
   elif kind.startswith('&'):
    lines += [f' nested_{field} := {convert(child,"*"+source)}',f' {target} = &nested_{field}']
   else:lines += [f' {target} = {convert(child,source)}']
  lines += [' return result','}','']
 return '\n'.join(lines),needed

def regenerate(root,check=False):
 content,needed=generate(root);file=root/'sdk/activation_payloads.v'
 content=formatted_source(content, file.name)
 if check:
  if file.read_text()!=content:raise RuntimeError('activation decoder differs from protobuf graph; regenerate')
 else:file.write_text(content)
 print(f'Activation payload decoder: {len(needed)} schema-derived types')

def main():
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 regenerate(Path(__file__).resolve().parent.parent,args.check)

if __name__=='__main__':main()
