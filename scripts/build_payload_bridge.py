"""Build the synchronous, schema-aware payload traversal library beside Core."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
from format_v import formatted_source
from urllib.parse import unquote, urlsplit


def signatures(rust):
    protos = rust / 'crates/protos/protos'
    for service, schema, package in (
        (1, 'api_upstream/temporal/api/workflowservice/v1/service.proto', 'temporal::api::workflowservice::v1::'),
        (2, 'api_upstream/temporal/api/operatorservice/v1/service.proto', 'temporal::api::operatorservice::v1::'),
        (3, 'api_cloud_upstream/temporal/api/cloud/cloudservice/v1/service.proto', 'temporal::api::cloud::cloudservice::v1::'),
        (4, 'testsrv_upstream/temporal/api/testservice/v1/service.proto', 'temporal::api::testservice::v1::'),
        (5, 'grpc/health/v1/health.proto', 'grpc::health::v1::'),
    ):
        text = (protos / schema).read_text()
        methods = re.findall(r'\brpc\s+(\w+)\s*\(\s*([\w.]+)\s*\)\s*returns\s*\(\s*([\w.]+)\s*\)', text)
        if not methods:
            raise RuntimeError(f'no methods found in {schema}')
        for method, request, response in methods:
            yield service, method, package, request, response


def generate(root, rust):
    lock = json.loads((root / 'locks/payload-messages.json').read_text())
    payload_types = set(lock['payload_types'])
    output = ['// Generated by scripts/build_payload_bridge.py from pinned service schemas.',
              'fn rpc_message(service: u32, method: &str, response: bool, input: &[u8], replacements: Option<Vec<Payload>>) -> Result<Vec<u8>, String> {',
              '    match (service, method, response) {']
    counts = {'directions': 0, 'payload_directions': 0, 'payload_types': len(payload_types)}
    for service, method, package, request, response in signatures(rust):
        for is_response, message in ((False, request), (True, response)):
            name = package + message
            expression = (f'visit_message::<temporalio_common::protos::{name}>'
                          if name in payload_types else 'visit_opaque')
            output.append(f'        ({service}, "{method}", {str(is_response).lower()}) => {expression}(input, replacements),')
            counts['directions'] += 1
            counts['payload_directions'] += name in payload_types
    output += ['        _ => Err("unknown RPC payload message".into()),', '    }', '}', '']
    destination = root / 'native/payloads/messages.rs'
    text = '\n'.join(output)
    if not destination.exists() or destination.read_text() != text:
        destination.write_text(text)
    return counts


def generate_targets(root, rust, check=False):
    messages = (root / 'temporal/core_pb.v').read_text()
    output = ['// Generated by scripts/build_payload_bridge.py from pinned request schemas.',
              'module sdk', '', 'import temporal_v.temporal', '',
              'fn client_storage_context(request ClientRpcRequest) !StorageContext {',
              '    if request.service != .workflow { return StorageContext{} }',
              '    match request.method {']
    for service, method, package, request, response in signatures(rust):
        if service != 1:
            continue
        name = 'TemporalApiWorkflowserviceV1_' + request
        match = re.search(r'^pub struct ' + name + r' \{(.*?)^\}', messages, re.S | re.M)
        if not match:
            raise RuntimeError('missing request schema: ' + name)
        fields = dict(re.findall(r'^\t(\w+)\s+([^\n/]+)', match[1], re.M))
        fields = {key: value.strip() for key, value in fields.items()}
        execution = next((field for field in ('execution', 'workflow_execution') if fields.get(field) == '?TemporalApiCommonV1_WorkflowExecution'), None)
        workflow_id = fields.get('workflow_id') == 'string'
        activity_id = fields.get('activity_id') == 'string'
        if fields.get('namespace') != 'string' or not (execution or workflow_id or activity_id):
            continue
        output += [f'        "{method}" {{', f'            message := temporal.{name}.decode(request.body)!']
        if execution:
            output += [f"            execution := message.{execution} or {{ temporal.TemporalApiCommonV1_WorkflowExecution{{}} }}",
                       '            workflow_id := execution.workflow_id', '            run_id := execution.run_id']
        else:
            output += ['            workflow_id := ' + ('message.workflow_id' if workflow_id else "''"),
                       '            run_id := ' + ('message.run_id' if fields.get('run_id') == 'string' else "''")]
        workflow_type = "''"
        if fields.get('workflow_type') == '?TemporalApiCommonV1_WorkflowType':
            output += ["            workflow_type := if value := message.workflow_type { value.name } else { '' }"]
            workflow_type = 'workflow_type'
        elif fields.get('workflow_type') == 'string':
            workflow_type = 'message.workflow_type'
        activity_type = "''"
        if fields.get('activity_type') == '?TemporalApiCommonV1_ActivityType':
            output += ["            activity_type := if value := message.activity_type { value.name } else { '' }"]
            activity_type = 'activity_type'
        elif fields.get('activity_type') == 'string':
            activity_type = 'message.activity_type'
        identifier = 'message.activity_id' if activity_id else "''"
        kind = '.workflow'
        if activity_id:
            output += ["            kind := if workflow_id == '' { SerializationKind.activity } else { SerializationKind.workflow }"]
            kind = 'kind'
        output += [f'            return StorageContext{{run_id: run_id, target: SerializationContext{{kind: {kind}, namespace: message.namespace, workflow_id: workflow_id, workflow_type: {workflow_type}, activity_id: {identifier}, activity_type: {activity_type}}}}}', '        }']
    output += ['        else { return StorageContext{} }', '    }', '}', '']
    destination = root / 'sdk/storage_targets.v'
    text = formatted_source('\n'.join(output), destination.name)
    if check:
        if destination.read_text() != text:
            raise RuntimeError('storage_targets.v differs from pinned request schemas; regenerate')
    elif not destination.exists() or destination.read_text() != text:
        destination.write_text(text)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--profile', choices=('debug', 'release'), default=os.environ.get('SPIKE_BUILD_PROFILE', 'debug'))
    parser.add_argument('--test', action='store_true')
    parser.add_argument('--library-only', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    artifacts = Path(os.environ.get('SPIKE_ARTIFACTS', root.parent / 'artifacts/v-sdk-spike')).resolve()
    test_binary = artifacts / 'tools/payload-bridge-tests'
    if args.test:
        if not test_binary.is_file():
            raise RuntimeError('native payload tests are not built; run scripts/build.sh')
        subprocess.run([str(test_binary)], check=True)
        return
    rust = artifacts / 'tools/sdk-rust'
    target = Path(os.environ.get('CARGO_TARGET_DIR', artifacts / 'rust-target')).resolve()
    counts = generate(root, rust)
    if not args.library_only:
        generate_targets(root, rust)
    lock = json.loads((root / 'locks/payload-messages.json').read_text())
    project = artifacts / 'payload-bridge'
    project.mkdir(exist_ok=True)
    manifest = '\n'.join([
        '[package]', 'name = "temporal-v-payloads"', 'version = "0.1.0"', 'edition = "2024"', 'publish = false',
        '', '[workspace]', '', '[lib]', 'crate-type = ["cdylib", "rlib"]',
        'path = ' + json.dumps(str(root / 'native/payloads/lib.rs')), '',
        '[[bin]]', 'name = "temporal-v-protobuf-oracle"', 'test = false', 'bench = false',
        'path = ' + json.dumps(str(root / 'native/payloads/protobuf_oracle.rs')), '', '[dependencies]',
        'prost = "=' + lock['prost'] + '"', 'futures-util = "=' + lock['futures_util'] + '"',
        'temporalio-common = { path = ' + json.dumps(str(rust / 'crates/common')) + ', features = ["core-based-sdk", "otel", "experimental", "vendored-protox"] }', '',
    ])
    manifest_path = project / 'Cargo.toml'
    if not manifest_path.exists() or manifest_path.read_text() != manifest:
        manifest_path.write_text(manifest)
    shutil.copy2(root / 'locks/payloads.Cargo.lock', project / 'Cargo.lock')
    env = dict(os.environ, RUSTUP_TOOLCHAIN=os.environ.get('SPIKE_RUST_TOOLCHAIN', '1.99.1'), CARGO_TARGET_DIR=str(target), CARGO_INCREMENTAL='0')
    command = [os.environ.get('CARGO_BIN', str(Path.home() / '.cargo/bin/cargo')), 'build',
               '--manifest-path', str(manifest_path), '--locked', '--lib']
    if args.profile == 'release':
        command.append('--release')
    built = subprocess.run(command + ['--message-format=json-render-diagnostics'], env=env, stdout=subprocess.PIPE, text=True)
    (artifacts / 'logs/payload-cargo.jsonl').write_text(built.stdout)
    built.check_returncode()
    # Other Core revisions and feature sets can coexist in Cargo's cache.
    # Validate the common crate actually selected by this build, so stale
    # build-script directories cannot reject or falsely validate the schema.
    graphs = set()
    common_source = (rust / 'crates/common').resolve()
    for line in built.stdout.splitlines():
        item = json.loads(line)
        package = item.get('package_id', '')
        if item.get('reason') != 'build-script-executed' or not package.startswith('path+'):
            continue
        source = urlsplit(package.split('#', 1)[0].removeprefix('path+'))
        if source.scheme == 'file' and Path(unquote(source.path)).resolve() == common_source:
            graphs.add(Path(item['out_dir']) / 'payload_visitor_impl.rs')
    if not graphs:
        raise RuntimeError('Cargo did not report the pinned common payload visitor output')
    expected = set(lock['payload_types'])
    graph_proof = []
    for graph in sorted(graphs):
        actual = set(re.findall(r'impl crate::payload_visitor::PayloadVisitable for crate::protos::([\w:]+)', graph.read_text()))
        if actual != expected:
            raise RuntimeError(f'active payload visitor graph changed: {graph}; missing={sorted(expected - actual)} extra={sorted(actual - expected)}')
        graph_proof.append({'path': str(graph), 'sha256': hashlib.sha256(graph.read_bytes()).hexdigest(), 'types': len(actual)})
    counts['payload_graphs'] = graph_proof
    if args.library_only:
        print(json.dumps(counts, sort_keys=True))
        return
    oracle_command = command.copy()
    oracle_command[1] = 'rustc'
    oracle_command.remove('--lib')
    oracle_command += ['--bin', 'temporal-v-protobuf-oracle', '--', '-C', 'debuginfo=0', '-C', 'strip=symbols']
    subprocess.run(oracle_command, env=env, check=True)
    shutil.copy2(target / args.profile / 'temporal-v-protobuf-oracle', artifacts / 'tools/protobuf-rust-oracle')
    # Compile tests while the build's target/registry caches are mounted. The
    # validation image runs this exact executable without downloading or
    # rebuilding Cargo dependencies.
    test_command = command.copy()
    test_command[1] = 'test'
    test_command += ['--no-run', '--message-format=json']
    result = subprocess.run(test_command, env=env, check=True, stdout=subprocess.PIPE, text=True)
    executables = []
    for line in result.stdout.splitlines():
        item = json.loads(line)
        if item.get('reason') == 'compiler-artifact' and item.get('target', {}).get('name') == 'temporal_v_payloads' and item.get('profile', {}).get('test') and item.get('executable'):
            executables.append(Path(item['executable']))
    if len(executables) != 1:
        raise RuntimeError('expected one native payload test executable')
    shutil.copy2(executables[0], test_binary)
    print(json.dumps(counts, sort_keys=True))


if __name__ == '__main__':
    main()
