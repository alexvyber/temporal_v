"""Generate typed unary RPC calls from actual pinned service signatures.

Messages are generated from the real request/response schemas. Reading only the
RPC signatures avoids importing HTTP/OpenAPI annotation extensions into vpbgen.
"""
import argparse
from pathlib import Path
import re
from format_v import formatted_source


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z][a-z]|(?<=[a-z0-9])[A-Z])', '_', name).lower()


def generate(root, rust, check=False):
    protos = rust / 'crates/protos/protos'
    services = [
        ('workflow', '', 'api_upstream/temporal/api/workflowservice/v1/service.proto', 'TemporalApiWorkflowserviceV1_'),
        ('operator', 'operator_', 'api_upstream/temporal/api/operatorservice/v1/service.proto', 'TemporalApiOperatorserviceV1_'),
        ('cloud', 'cloud_', 'api_cloud_upstream/temporal/api/cloud/cloudservice/v1/service.proto', 'TemporalApiCloudCloudserviceV1_'),
        ('test', 'test_', 'testsrv_upstream/temporal/api/testservice/v1/service.proto', 'TemporalApiTestserviceV1_'),
        ('health', 'health_', 'grpc/health/v1/health.proto', 'GrpcHealthV1_'),
    ]
    messages = (root / 'temporal/core_pb.v').read_text()
    bridge = (rust / 'crates/sdk-core-c-bridge/src/client.rs').read_text()
    counts = {}
    for service, method_prefix, schema, type_prefix in services:
        signatures = re.findall(r'\brpc\s+(\w+)\s*\(\s*([\w.]+)\s*\)\s*returns\s*\(\s*([\w.]+)\s*\)', (protos / schema).read_text())
        if not signatures:
            raise RuntimeError(f'{service}: no unary RPCs found')
        output = ['// Generated by scripts/generate_service.py from pinned service schemas.',
                  '// Low-level calls use explicit namespace/options in their generated request.',
                  'module sdk', '', 'import temporal', '']
        for method, request, response in signatures:
            if '"' + method + '"' not in bridge:
                raise RuntimeError(f'{service}.{method}: missing Rust RPC dispatcher')
            def message_type(name):
                if name == 'google.protobuf.Empty':
                    return 'GoogleProtobuf_Empty'
                return type_prefix + name
            request = message_type(request)
            response = message_type(response)
            for message in (request, response):
                if not re.search(r'^pub struct ' + message + r'\s*\{', messages, re.MULTILINE):
                    raise RuntimeError(f'{service}.{method}: {message} was not generated')
            output += [f'pub fn (client &Client) rpc_{method_prefix}{snake(method)}(request temporal.{request}) !temporal.{response} {{',
                       f"\treturn temporal.{response}.decode(client.call(.{service}, '{method}', request.encode())!)!", '}', '']
        filename = 'time_skipping_service.v' if service == 'test' else f'{service}_service.v'
        destination = root / 'sdk' / filename
        content = formatted_source('\n'.join(output), filename)
        if check:
            if destination.read_text() != content:
                raise RuntimeError(f'{filename}: generated RPC methods differ; regenerate')
        else:
            destination.write_text(content)
        counts[service] = len(signatures)
    print('Generated typed RPC methods: ' + ', '.join(f'{name}={count}' for name, count in counts.items()))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--rust', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(Path(__file__).resolve().parent.parent, args.rust, args.check)


if __name__ == '__main__':
    main()
